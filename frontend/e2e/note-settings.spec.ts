import { test, expect } from '@playwright/test';

test('FEAT-005 dictionary, presentation and notebook are centralized with explicit scopes and independent saves', async ({ page, request }) => {
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('owner@e2e.invalid');
  await page.getByLabel('Password', { exact: true }).fill(process.env['RECCE_E2E_PASSWORD']!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page).toHaveURL(/\/pecs$/);
  await page.getByRole('link', { name: 'Perfil da Equipa', exact: true }).click();
  await expect(page.locator('app-team-profile')).toBeVisible();
  await expect(page.locator('app-team-profile app-notebook-settings')).toHaveCount(0);
  await expect(page.getByText('Sistema de Notas Base', { exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Notas', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Configurar notas', exact: true })).toBeVisible();
  await expect(page.getByText('Partilhado com a equipa', { exact: true })).toBeVisible();
  const api = 'http://127.0.0.1:18765/api';
  await page.locator('[data-tour="note-system"] > summary').click();
  await page.getByRole('textbox', { name: 'Sistema de notas base', exact: true }).fill('Sistema centralizado 1–6');
  const systemWrite = page.waitForResponse(response => response.url() === `${api}/team-profile` && response.request().method() === 'PATCH');
  await page.getByRole('button', { name: 'Guardar sistema base da equipa', exact: true }).click();
  const systemResponse = await systemWrite;
  expect(systemResponse.status()).toBe(200);
  expect(systemResponse.request().postDataJSON()).toEqual({ noteSystem: 'Sistema centralizado 1–6' });

  const form = page.locator('app-notes form');
  await form.getByLabel(/Quando digo/i).fill('curva centralizada');
  await form.getByLabel(/Significado/i).fill('Curva pessoal de teste');
  await form.getByLabel(/Escrever/i).fill('Z6');
  await form.getByLabel(/Grupo/i).fill('curvas');
  const dictionaryWrite = page.waitForResponse(response => response.url() === `${api}/note-dictionary-rules` && response.request().method() === 'POST');
  await form.getByRole('button', { name: 'Adicionar', exact: true }).click();
  expect((await dictionaryWrite).status()).toBe(200);
  const row = page.locator('.note-rule-row').filter({ hasText: 'curva centralizada' });
  await expect(row).toContainText('Z6'); await expect(row).toContainText('Curva pessoal de teste');
  await row.getByRole('button', { name: 'Configurar apresentação de Z6', exact: true }).click();
  const personal = page.locator('app-notebook-settings');
  await expect(personal.getByText('Pessoal', { exact: true })).toBeVisible();
  const style = personal.locator('details').filter({ has: page.locator('summary', { hasText: /^Z6 →/ }) });
  await expect(style.getByLabel('Correspondência', { exact: true })).toHaveValue('Z6');
  await style.getByLabel('Posição', { exact: true }).selectOption('bottom-left');
  await style.getByLabel('Negrito', { exact: true }).check();
  await page.getByRole('button', { name: 'Caderno e exportação', exact: true }).click();
  await personal.getByLabel('Linhas por página', { exact: true }).fill('6');
  await page.getByRole('button', { name: 'Dicionário', exact: true }).click();
  await row.getByRole('button', { name: 'Configurar apresentação de Z6', exact: true }).click();
  await expect(style.getByLabel('Posição', { exact: true })).toHaveValue('bottom-left');
  await expect(style.getByLabel('Negrito', { exact: true })).toBeChecked();
  await expect(personal.locator('details').filter({ has: page.locator('summary', { hasText: /^Z6 →/ }) })).toHaveCount(1);
  const notebookWrite = page.waitForResponse(response => response.url() === `${api}/notebook-preferences` && response.request().method() === 'PUT');
  await personal.getByRole('button', { name: 'Guardar modelo pessoal', exact: true }).click();
  const notebookResponse = await notebookWrite; expect(notebookResponse.status()).toBe(200);
  expect(notebookResponse.request().postDataJSON().page.rowsPerPage).toBe(6);
  await page.reload();
  await page.locator('[data-tour="note-system"] > summary').click();
  await expect(page.getByRole('textbox', { name: 'Sistema de notas base', exact: true })).toHaveValue('Sistema centralizado 1–6');
  await expect(row).toContainText('Curva pessoal de teste');
  await row.getByRole('button', { name: 'Configurar apresentação de Z6', exact: true }).click();
  await expect(style.getByLabel('Posição', { exact: true })).toHaveValue('bottom-left');
  await page.getByRole('button', { name: 'Caderno e exportação', exact: true }).click();
  await expect(personal.getByLabel('Linhas por página', { exact: true })).toHaveValue('6');
  await expect(personal.locator('.notebook-pages')).toContainText('Z6');
  await page.screenshot({ path: '../.factory-results/FEAT-005-centralized.png', fullPage: true });
  await page.getByRole('link', { name: 'Perfil da Equipa', exact: true }).click();
  await page.getByRole('button', { name: 'Editar Perfil', exact: true }).click();
  await page.getByLabel('Nome da equipa', { exact: true }).fill('E2E owner');
  const profileWrite = page.waitForResponse(response => response.url() === `${api}/team-profile` && response.request().method() === 'PATCH');
  await page.getByRole('button', { name: 'Guardar', exact: true }).click();
  const profileResponse = await profileWrite;
  expect(profileResponse.status()).toBe(200);
  expect(profileResponse.request().postDataJSON()).not.toHaveProperty('noteSystem');
  expect((await profileResponse.json()).noteSystem).toBe('Sistema centralizado 1–6');
  // Read persistence through HTTP as well as UI; no API mocking or permission bypass.
  const token = await page.evaluate(() => localStorage.getItem('recce_auth_token'));
  const headers = { Authorization: `Bearer ${token}` };
  const saved = await request.get(`${api}/notebook-preferences`, { headers });
  expect(saved.ok()).toBeTruthy();
  expect((await saved.json()).rules.filter((rule: {match: string}) => rule.match === 'Z6')).toHaveLength(1);
});
