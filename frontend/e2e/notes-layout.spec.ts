import { test, expect } from '@playwright/test';

test('FEAT-008 Notes keeps routine controls prominent and help available on demand', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('owner@e2e.invalid');
  await page.getByLabel('Password', { exact: true }).fill(process.env['RECCE_E2E_PASSWORD']!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page).toHaveURL(/\/pecs$/);
  const writes: string[] = [];
  page.on('request', req => { if (req.url().includes('/api/') && !['GET', 'HEAD', 'OPTIONS'].includes(req.method())) writes.push(req.method()); });
  await page.getByRole('link', { name: 'Notas', exact: true }).click();
  const notes = page.locator('app-notes');
  const help = notes.locator('.notes-help');
  await expect(help).not.toHaveAttribute('open', '');
  await expect(notes.locator('[data-tour="note-system"]')).not.toHaveAttribute('open', '');
  const header = await notes.locator('.notes-header').boundingBox();
  expect(header!.height).toBeLessThan(120);
  await help.locator('summary').focus(); await page.keyboard.press('Enter');
  await expect(help.getByRole('link', { name: 'Mostrar ajuda guiada', exact: true })).toBeVisible();
  await expect(help).toContainText('Guarda as edições');
  await page.keyboard.press('Enter');
  await expect(help.getByRole('link', { name: 'Mostrar ajuda guiada', exact: true })).toBeHidden();
  await page.getByRole('button', { name: 'Apresentação', exact: true }).click();
  const personal = notes.locator('app-notebook-settings');
  await expect(personal.locator('.scope-label')).toHaveText('Pessoal');
  await expect(personal.locator('.dictionary > details.rule')).toHaveCount(0);
  await expect(personal.getByRole('button', { name: 'Guardar modelo pessoal', exact: true })).toBeVisible();
  await expect(personal.getByRole('button', { name: 'Repor modelo inicial', exact: true })).toBeHidden();
  const context = personal.locator('.context-help');
  await context.locator('summary').focus(); await page.keyboard.press('Enter');
  await expect(context).toContainText('Os símbolos e significados vêm do Dicionário');
  await page.keyboard.press('Enter');
  const select = personal.getByLabel('Símbolo do Dicionário', { exact: true });
  await select.selectOption('E6');
  const editor = personal.locator('.dictionary > details.rule');
  await expect(editor).toHaveCount(1);
  await editor.getByLabel('Tamanho relativo (%)', { exact: true }).fill('115');
  await select.selectOption('D6'); await expect(editor).toHaveCount(1);
  await select.selectOption('E6');
  await expect(editor.getByLabel('Tamanho relativo (%)', { exact: true })).toHaveValue('115');
  await page.screenshot({ path: '../.factory-results/FEAT-008-desktop.png', fullPage: false });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await expect(select).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: '../.factory-results/FEAT-008-mobile.png', fullPage: false });
  expect(writes).toEqual([]);
});
