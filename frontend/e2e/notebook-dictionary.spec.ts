import { test, expect } from '@playwright/test';

test('FEAT-007 presentation is defined by dictionary symbols and retains historical layouts after rename', async ({ page, request }) => {
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('owner@e2e.invalid');
  await page.getByLabel('Password', { exact: true }).fill(process.env['RECCE_E2E_PASSWORD']!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page).toHaveURL(/\/pecs$/);
  await page.getByRole('link', { name: 'Notas', exact: true }).click();
  const form = page.locator('app-notes form');
  await form.getByLabel(/Quando digo/i).fill('símbolo com origem única');
  await form.getByLabel(/Escrever/i).fill('N7');
  await form.getByLabel(/Significado/i).fill('Definido no dicionário');
  const create = page.waitForResponse(response => response.url().endsWith('/api/note-dictionary-rules') && response.request().method() === 'POST');
  await form.getByRole('button', { name: 'Adicionar', exact: true }).click();
  expect((await create).ok()).toBeTruthy();
  await page.locator('.note-rule-row').filter({ hasText: 'símbolo com origem única' }).getByRole('button', { name: 'Configurar apresentação de N7', exact: true }).click();
  const personal = page.locator('app-notebook-settings');
  await expect(personal.getByRole('button', { name: 'Adicionar elemento', exact: true })).toHaveCount(0);
  await expect(personal.getByRole('button', { name: /^Remover elemento/ })).toHaveCount(0);
  const style = personal.locator('details.rule').filter({ has: page.locator('summary', { hasText: /^N7 →/ }) });
  for (const label of ['Correspondência', 'Símbolo apresentado', 'Significado']) {
    await expect(style.getByLabel(label, { exact: true })).toHaveAttribute('readonly', '');
  }
  await expect(style.getByLabel('Símbolo apresentado', { exact: true })).toHaveValue('N7');
  await expect(style.getByLabel('Significado', { exact: true })).toHaveValue('Definido no dicionário');
  await style.getByLabel('Posição', { exact: true }).selectOption('bottom-left');
  await style.getByLabel('Tamanho relativo (%)', { exact: true }).fill('110');
  const save = page.waitForResponse(response => response.url().endsWith('/api/notebook-preferences') && response.request().method() === 'PUT');
  await personal.getByRole('button', { name: 'Guardar modelo pessoal', exact: true }).click();
  expect((await save).ok()).toBeTruthy();
  await page.reload();
  await page.getByRole('button', { name: 'Apresentação', exact: true }).click();
  await personal.getByLabel('Símbolo do Dicionário', { exact: true }).selectOption('N7');
  await expect(style.getByLabel('Posição', { exact: true })).toHaveValue('bottom-left');
  await expect(style.getByLabel('Tamanho relativo (%)', { exact: true })).toHaveValue('110');
  await page.screenshot({ path: '../.factory-results/FEAT-007-presentation.png', fullPage: false });
  await personal.getByRole('button', { name: 'Ir ao Dicionário', exact: true }).click();
  await expect(form).toBeVisible();
  await page.locator('.note-rule-row').filter({ hasText: 'símbolo com origem única' }).getByRole('button', { name: 'Editar', exact: true }).click();
  await form.getByLabel(/Escrever/i).fill('N8');
  await form.getByLabel(/Significado/i).fill('Alterado apenas no dicionário');
  const rename = page.waitForResponse(response => response.url().includes('/api/note-dictionary-rules/') && response.request().method() === 'PATCH');
  await form.getByRole('button', { name: 'Guardar', exact: true }).click();
  expect((await rename).ok()).toBeTruthy();
  await page.getByRole('button', { name: 'Apresentação', exact: true }).click();
  const symbols = personal.getByLabel('Símbolo do Dicionário', { exact: true });
  await expect(symbols.locator('option[value="N7"]')).toHaveCount(0);
  await expect(symbols.locator('option[value="N8"]')).toHaveCount(1);
  await expect(style).toHaveCount(0);
  const historical = personal.locator('.secondary-options details.rule').filter({ has: page.locator('summary', { hasText: /^Apresentações anteriores/ }) });
  await personal.locator('.secondary-options > summary').click();
  await historical.locator('summary').click();
  await expect(historical).toContainText('N7 → N7');
  await symbols.selectOption('N8');
  const renamed = personal.locator('details.rule').filter({ has: page.locator('summary', { hasText: /^N8 →/ }) });
  await expect(renamed.getByLabel('Significado', { exact: true })).toHaveValue('Alterado apenas no dicionário');
  const saveRenamed = page.waitForResponse(response => response.url().endsWith('/api/notebook-preferences') && response.request().method() === 'PUT');
  await personal.getByRole('button', { name: 'Guardar modelo pessoal', exact: true }).click();
  expect((await saveRenamed).ok()).toBeTruthy();
  const token = await page.evaluate(() => localStorage.getItem('recce_auth_token'));
  const preferences = await request.get('http://127.0.0.1:18765/api/notebook-preferences', { headers: { Authorization: `Bearer ${token}` } });
  expect(preferences.ok()).toBeTruthy();
  const saved = await preferences.json();
  expect(saved.rules.find((rule: {match: string}) => rule.match === 'N7')).toMatchObject({ position: 'bottom-left', size: 110 });
  expect(saved.rules.filter((rule: {match: string}) => rule.match === 'N8')).toHaveLength(1);
});
