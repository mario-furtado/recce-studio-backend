import { test, expect } from '@playwright/test';

test('FEAT-014 Studio layout, mobile views, keyboard, draft exits and media continuity', async ({ page, request }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/login'); await page.getByLabel('Email', { exact: true }).fill('owner@e2e.invalid');
  await page.getByLabel('Password', { exact: true }).fill(process.env['RECCE_E2E_PASSWORD']!);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click(); await expect(page).toHaveURL(/\/pecs$/);
  const api = 'http://127.0.0.1:18765/api';
  const headers = { Authorization: `Bearer ${await page.evaluate(() => localStorage.getItem('recce_auth_token'))}` };
  const rallyResponse = await request.post(`${api}/rallies`, { headers, data: { name: 'Redesign fixture', year: 2026, location: 'Serra', surface: 'TERRA' } });
  expect(rallyResponse.ok()).toBeTruthy(); const rally = await rallyResponse.json();
  const pecResponse = await request.post(`${api}/rallies/${rally.id}/pecs`, { headers, data: { name: 'Serra do Studio', number: 1, distanceKm: 8.5 } });
  expect(pecResponse.ok()).toBeTruthy(); const pec = await pecResponse.json();
  for (const [at, text] of ['D6 ATT', 'E3 60', 'D4 NC'].entries()) expect((await request.post(`${api}/pecs/${pec.id}/notes`, { headers, data: { text, originalTimestamp: .3 + at * .5, latitude: 40.1 + at * .001, longitude: -8.1 } })).ok()).toBeTruthy();
  const bytes = await page.evaluate(async () => {
    const canvas = document.createElement('canvas'); canvas.width = 160; canvas.height = 90;
    const ctx = canvas.getContext('2d')!; const stream = canvas.captureStream(10); const recorder = new MediaRecorder(stream, { mimeType: 'video/webm;codecs=vp8' });
    const chunks: Blob[] = []; recorder.ondataavailable = event => chunks.push(event.data);
    const done = new Promise<Blob>(resolve => { recorder.onstop = () => resolve(new Blob(chunks, { type: 'video/webm' })); });
    const timer = setInterval(() => { ctx.fillStyle = '#3b526b'; ctx.fillRect(0, 0, 160, 90); }, 100);
    recorder.start(); await new Promise(resolve => setTimeout(resolve, 2200)); recorder.stop(); clearInterval(timer);
    const blob = await done; stream.getTracks().forEach(track => track.stop()); return Array.from(new Uint8Array(await blob.arrayBuffer()));
  });
  expect((await request.post(`${api}/pecs/${pec.id}/video`, { headers, multipart: { file: { name: 'review.webm', mimeType: 'video/webm', buffer: Buffer.from(bytes) } } })).ok()).toBeTruthy();
  await page.route('https://services.arcgisonline.com/**', route => route.abort());
  await page.goto(`/recce/${pec.id}`); await page.getByRole('button', { name: 'Studio', exact: true }).click();
  await expect.poll(() => page.locator('video').evaluate(element => (element as HTMLVideoElement).readyState)).toBeGreaterThanOrEqual(2);
  const notes = page.locator('.studio-notes'), review = page.locator('.studio-review');
  await expect(page.locator('.note-row')).toHaveCount(3);
  await expect(page.locator('.notes-heading .studio-primary')).toHaveCSS('background-color', 'rgb(189, 18, 52)');
  await expect(page.getByRole('navigation', { name: 'Vistas do Studio' })).toBeHidden();
  const files = page.locator('.studio-tools > details').filter({ has: page.locator('summary', { hasText: /^Ficheiros$/ }) });
  await files.locator('summary').click();
  await expect(files.getByLabel('Importar notas', { exact: true })).toBeEnabled();
  const downloadPromise = page.waitForEvent('download');
  await files.getByRole('button', { name: 'Exportar notas em Excel', exact: true }).click();
  expect((await downloadPromise).suggestedFilename()).toMatch(/\.xlsx$/);
  await expect(files.locator('[popover]')).toBeHidden();
  const contrast = await page.locator('.notes-heading .studio-primary').evaluate(button => {
    const style = getComputedStyle(button);
    const luminance = (color: string) => color.match(/\d+/g)!.slice(0, 3).map(value => { const c = Number(value) / 255; return c <= .04045 ? c / 12.92 : ((c + .055) / 1.055) ** 2.4; }).reduce((sum, value, index) => sum + value * [.2126, .7152, .0722][index], 0);
    const a = luminance(style.color), b = luminance(style.backgroundColor);
    return (Math.max(a, b) + .05) / (Math.min(a, b) + .05);
  });
  expect(contrast).toBeGreaterThanOrEqual(4.5);
  expect((await review.boundingBox())!.x + (await review.boundingBox())!.width).toBeLessThan((await notes.boundingBox())!.x);
  await page.locator('.desktop-options summary').click(); const width = page.getByLabel('Largura do painel de notas', { exact: true });
  const beforeWidth = (await notes.boundingBox())!.width; await width.focus(); await page.keyboard.press('ArrowRight');
  await expect.poll(async () => (await notes.boundingBox())!.width).toBeGreaterThan(beforeWidth);
  await page.locator('.desktop-options summary').click();
  await page.screenshot({ path: '../.factory-results/FEAT-014-studio-desktop.png', fullPage: true });
  const first = page.locator('.note-row').first(); await first.getByRole('button', { name: /^Rever nota/ }).click();
  const video = page.locator('video');
  await video.evaluate(element => { const media = element as HTMLVideoElement; media.pause(); media.currentTime = .6; Reflect.set(window, '__studioVideo', element); });
  await expect(first.getByRole('button', { name: /^Rever nota/ })).toHaveAttribute('aria-current', 'true');
  await first.getByRole('button', { name: 'Editar', exact: true }).click();
  const editor = page.locator('.note-editor');
  await expect(editor.getByRole('button', { name: 'Guardar', exact: true })).toHaveCSS('background-color', 'rgb(189, 18, 52)');
  await expect(page.getByLabel('Texto da nota', { exact: true })).toBeFocused();
  await expect(page.getByLabel('Texto da nota', { exact: true })).toHaveCSS('outline-width', '3px');
  await expect(page.locator('.notes-list')).toBeHidden();
  await page.getByLabel('Texto da nota', { exact: true }).fill('D6 ATT especial');
  await editor.getByRole('button', { name: 'Voltar às notas', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Descartar alterações?' })).toBeVisible();
  await page.getByRole('button', { name: 'Continuar a editar', exact: true }).click();
  await expect(page.getByLabel('Texto da nota', { exact: true })).toHaveValue('D6 ATT especial');
  await page.getByRole('button', { name: 'Visão Geral', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Descartar alterações?' })).toBeVisible();
  await page.getByRole('button', { name: 'Continuar a editar', exact: true }).click();
  await expect(page.getByLabel('Texto da nota', { exact: true })).toHaveValue('D6 ATT especial');
  await page.getByRole('link', { name: 'Tutorial', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Descartar alterações?' })).toBeVisible();
  await page.getByRole('button', { name: 'Continuar a editar', exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/recce/${pec.id}$`));
  expect(await page.evaluate(() => { const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); return event.defaultPrevented; })).toBeTruthy();
  await editor.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(first.getByRole('button', { name: 'Editar', exact: true })).toBeFocused();
  await first.locator('.note-actions summary').click(); await first.getByRole('button', { name: 'Eliminar nota', exact: true }).click();
  await expect(page.getByRole('dialog', { name: /Eliminar/ })).toBeVisible(); await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(page.locator('.note-row')).toHaveCount(3);
  for (const screenWidth of [360, 390]) {
    await page.setViewportSize({ width: screenWidth, height: 844 });
    const tabs = page.getByRole('navigation', { name: 'Vistas do Studio', exact: true });
    await tabs.getByRole('button', { name: 'Vídeo', exact: true }).click(); await expect(video).toBeVisible();
    await tabs.getByRole('button', { name: 'Mapa', exact: true }).click(); await expect(page.locator('.leaflet-container')).toBeVisible();
    await tabs.getByRole('button', { name: 'Notas', exact: true }).click(); await expect(notes).toBeVisible();
    expect(await video.evaluate(element => element === Reflect.get(window, '__studioVideo'))).toBeTruthy();
    expect(await video.evaluate(element => (element as HTMLVideoElement).currentTime)).toBeCloseTo(.6, 1);
    const box = await notes.boundingBox(); expect(box!.x).toBeGreaterThanOrEqual(0); expect(box!.x + box!.width).toBeLessThanOrEqual(screenWidth);
  }
  await first.getByRole('button', { name: 'Editar', exact: true }).click();
  await editor.getByLabel('Texto da nota', { exact: true }).fill('D6 ATT móvel');
  await page.setViewportSize({ width: 390, height: 500 });
  const save = editor.getByRole('button', { name: 'Guardar', exact: true }); await save.scrollIntoViewIfNeeded();
  const saveBox = await save.boundingBox(), sessionBar = await page.locator('.mobile-session-bar').boundingBox();
  expect(saveBox!.y + saveBox!.height).toBeLessThanOrEqual(sessionBar!.y);
  await expect(save).toBeEnabled(); await save.focus(); await page.keyboard.press('Shift+Tab');
  await expect(editor.getByRole('button', { name: 'Cancelar', exact: true })).toBeFocused();
  await page.screenshot({ path: '../.factory-results/FEAT-014-studio-mobile-keyboard.png', fullPage: false });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '../.factory-results/FEAT-014-studio-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Visão Geral', exact: true }).click();
  await page.getByRole('button', { name: 'Descartar', exact: true }).click();
  await expect(editor).toHaveCount(0);
  const persisted = await (await request.get(`${api}/pecs/${pec.id}/notes`, { headers })).json();
  expect(persisted[0].text).toBe('D6 ATT');
});
