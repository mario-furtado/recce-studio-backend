    @Test void offlineCliDoesNotOpenAnAlreadyRunningFileDatabaseOrIgnoreOptions() throws Exception {
        Path plan=temporary.resolve("blocked-plan.json");
        assertEquals(1,runCli(plan,false));assertFalse(Files.exists(plan));assertEquals(2,count("auth_users"));
        db.close();assertEquals(1,runCli(plan,true));assertFalse(Files.exists(plan));
        assertEquals(0,runCli(plan,false));assertEquals(2,read(plan).path("contexts").size());
    }
    int runCli(Path plan,boolean unknown) throws Exception {
        String javaExecutable=Paths.get(System.getProperty("java.home"),"bin",System.getProperty("os.name").startsWith("Windows")?"java.exe":"java").toString();
        List<String> args=new ArrayList<>(Arrays.asList(javaExecutable,"-cp",System.getProperty("java.class.path"),LegacyCrewMigrationTool.class.getName(),"plan","--database",database.toString(),"--media",media.toString(),"--out",plan.toString()));
        if(unknown)args.addAll(Arrays.asList("--unknown","true"));
        ProcessBuilder builder=new ProcessBuilder(args).redirectErrorStream(true).redirectOutput(temporary.resolve("cli.log").toFile());
        builder.environment().put("RECCE_MIGRATION_DB_USER","sa");builder.environment().put("RECCE_MIGRATION_DB_PASSWORD","");Process process=builder.start();
        if(!process.waitFor(30,java.util.concurrent.TimeUnit.SECONDS)){process.destroyForcibly();fail("Offline fixture CLI did not finish.");}
        return process.exitValue();
    }
