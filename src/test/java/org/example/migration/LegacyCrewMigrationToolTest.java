    @BeforeEach void setup() throws Exception {
        database=temporary.resolve("source");media=Files.createDirectory(temporary.resolve("media"));
        db=DriverManager.getConnection("jdbc:h2:file:"+database,"sa","");
        try(Statement s=db.createStatement()) {
            s.execute("create table auth_users(id varchar primary key,email varchar,password_hash varchar,token varchar,active boolean,team_profile_id varchar)");
            s.execute("create table team_profile(id varchar primary key,name varchar,note_system varchar,logo_storage_path varchar)");
            s.execute("create table rallies(id varchar primary key,team_profile_id varchar,name varchar,car_id varchar)");
            s.execute("create table pecs(id varchar primary key,rally_id varchar,name varchar,audio_storage_path varchar)");
            s.execute("create table notes(id bigint generated by default as identity primary key,pec_id varchar,text varchar)");
            s.execute("create table team_cars(id varchar primary key,team_profile_id varchar,name varchar,photo_storage_path varchar)");
            s.execute("create table offline_recce_syncs(id varchar primary key,team_profile_id varchar,pec_id varchar,offline_session_id varchar)");
            s.execute("create table private_settings(user_id varchar primary key,settings clob)");
        }
        for(String id:Arrays.asList("a","b")) {
            LegacyCrewMigrationTool.update(db,"insert into auth_users values(?,?,?,?,?,?)","user-"+id,id+"@fixture.invalid","unchanged-hash-"+id,"secret-session-"+id,true,"team-"+id);
            LegacyCrewMigrationTool.update(db,"insert into team_profile values(?,?,?,null)","team-"+id,"Team "+id,"1-6");
            LegacyCrewMigrationTool.update(db,"insert into rallies values(?,?,?,null)","rally-"+id,"team-"+id,"Rally "+id);
            Path audio=media.resolve(id+".webm");Files.write(audio,new byte[]{1,2,3,(byte)id.charAt(0)});
            LegacyCrewMigrationTool.update(db,"insert into pecs values(?,?,?,?)","pec-"+id,"rally-"+id,"PEC "+id,audio.toString());
            LegacyCrewMigrationTool.update(db,"insert into notes(pec_id,text) values(?,?)","pec-"+id,"E3 "+id);
            LegacyCrewMigrationTool.update(db,"insert into offline_recce_syncs values(?,?,?,?)","receipt-"+id,"team-"+id,"pec-"+id,"offline-session-"+id);
            LegacyCrewMigrationTool.update(db,"insert into private_settings values(?,?)","user-"+id,"{\"private\":\""+id+"\"}");
        }
    }
    @AfterEach void close() throws Exception {if(db!=null&&!db.isClosed())db.close();}
    void prepare() throws Exception {
        ObjectNode plan=LegacyCrewMigrationTool.plan(db,media); ObjectNode approved=JSON.createObjectNode().put("version",1).put("approvedBy","isolated-test-operator").put("approvalReference","approved-test-fixture");
        ArrayNode entries=approved.putArray("entries");
        for(JsonNode ctx:plan.path("contexts")) {
            ObjectNode entry=entries.addObject().put("teamProfileId",ctx.path("teamProfileId").asText()).put("ownerAccountId",ctx.path("candidateAccountIds").path(0).asText()).put("expectedDigest",ctx.path("digest").asText()); entry.set("legacyAccountIds",ctx.path("candidateAccountIds").deepCopy());
        }
        manifest=temporary.resolve("manifest.json");writeNew(manifest,approved);digest=fileHash(manifest);
        backup=temporary.resolve("backup");MigrationSnapshot.backup(db,media,backup);
        restore=temporary.resolve("restore");MigrationSnapshot.restoreCheck(backup,restore,"sa","");
    }
    ObjectNode apply(int batch) throws Exception {return LegacyCrewMigrationTool.apply(db,media,manifest,digest,backup,restore.resolve("restore-proof.json"),"sa","",batch);}
    long count(String table) throws Exception {return LegacyCrewMigrationTool.count(db,"select count(*) from "+table);}
    @Test void backsUpAndRestoresRealDatabaseAndMediaWithoutChangingTheSource() throws Exception {
        String before=databaseHash(db);prepare();assertEquals(before,databaseHash(db));
        try(Connection restored=LegacyCrewMigrationTool.connect(restore.resolve("restored"),"sa","")) {assertEquals(before,databaseHash(restored));assertEquals(2,LegacyCrewMigrationTool.count(restored,"select count(*) from notes"));}
        assertArrayEquals(Files.readAllBytes(media.resolve("a.webm")),Files.readAllBytes(restore.resolve("media/a.webm")));
        assertThrows(IllegalArgumentException.class,()->MigrationSnapshot.restoreCheck(backup,restore,"sa",""));
    }
    @Test void convertsInBatchesAndResumesAfterReopenWithoutDuplicatingOrOverwritingNewData() throws Exception {
        prepare();assertEquals(1,apply(1).path("converted").asInt());
        LegacyCrewMigrationTool.update(db,"insert into notes(pec_id,text) values('pec-a','New after migration')");
        db.close();db=LegacyCrewMigrationTool.connect(database,"sa","");assertEquals(1,apply(1).path("converted").asInt());assertEquals(0,apply(10).path("converted").asInt());
        assertEquals(2,count("crews"));assertEquals(2,count("legacy_crew_migrations"));assertEquals(2,count("offline_recce_syncs"));assertEquals(3,count("notes"));
        assertEquals(2,LegacyCrewMigrationTool.count(db,"select count(*) from auth_users where legacy_crew_migrated=true and team_profile_id is null"));
        assertEquals(1,LegacyCrewMigrationTool.count(db,"select count(*) from auth_users where id='user-a' and password_hash='unchanged-hash-a' and token='secret-session-a'"));
        assertEquals(2,count("private_settings"));assertEquals(2,LegacyCrewMigrationTool.count(db,"select count(*) from legacy_crew_migrations where approved_by='isolated-test-operator'"));
    }
    @Test void failureMidContextRollsBackWhileCommittedContextCanResume() throws Exception {
        prepare();LegacyCrewMigrationTool.schema(db);
        try(Statement s=db.createStatement()){s.execute("alter table legacy_crew_migrations add constraint fixture_failure check(team_profile_id <> 'team-b')");}
        assertThrows(SQLException.class,()->apply(10)); assertEquals(1,count("crews"));assertEquals(1,count("legacy_crew_migrations"));
        assertEquals(1,LegacyCrewMigrationTool.count(db,"select count(*) from auth_users where id='user-b' and team_profile_id='team-b' and legacy_crew_migrated is null"));
        try(Statement s=db.createStatement()){s.execute("alter table legacy_crew_migrations drop constraint fixture_failure");}
        assertEquals(1,apply(10).path("converted").asInt()); assertEquals(2,count("crews"));assertEquals(2,count("notes"));
    }
    @Test void changedSourceWrongOwnerAndAdditionalMembersNeverGetInferred() throws Exception {
        prepare();LegacyCrewMigrationTool.update(db,"insert into auth_users values('other','other@fixture.invalid','hash','token',true,'team-a')");
        assertThrows(IllegalArgumentException.class,()->apply(10)); assertEquals(0,count("crews"));
        assertEquals(2,LegacyCrewMigrationTool.count(db,"select count(*) from auth_users where team_profile_id='team-a'"));
        LegacyCrewMigrationTool.update(db,"delete from auth_users where id='other'");
        ObjectNode changed=(ObjectNode)read(manifest);((ObjectNode)changed.path("entries").get(0)).put("ownerAccountId","user-b");
        Files.write(manifest,JSON.writeValueAsBytes(changed));digest=fileHash(manifest);assertThrows(IllegalArgumentException.class,()->apply(10));assertEquals(0,count("crews"));
    }
    @Test void missingOrChangedMediaAndInactiveOwnerBlockCutover() throws Exception {
        prepare();Files.write(media.resolve("a.webm"),new byte[]{9});assertThrows(IllegalArgumentException.class,()->apply(10));assertEquals(0,count("crews"));
        Files.delete(media.resolve("a.webm"));assertTrue(LegacyCrewMigrationTool.plan(db,media).path("contexts").get(0).path("blockingReasons").toString().contains("MEDIA_MISSING"));
        LegacyCrewMigrationTool.update(db,"update auth_users set active=false where id='user-b'");
        assertTrue(LegacyCrewMigrationTool.plan(db,media).path("contexts").get(1).path("blockingReasons").toString().contains("OWNER_INACTIVE"));
    }
    @Test void backupOrProofTamperingAndUnreviewedManifestAreRejected() throws Exception {
        prepare();assertThrows(IllegalArgumentException.class,()->LegacyCrewMigrationTool.apply(db,media,manifest,"incorrect-digest",backup,restore.resolve("restore-proof.json"),"sa","",10));
        Files.write(restore.resolve("media/a.webm"),new byte[]{0});assertThrows(IllegalArgumentException.class,()->apply(10));assertFalse(tables(db).contains("LEGACY_CREW_MIGRATIONS"));
        Files.write(backup.resolve("database.sql"),"tampered".getBytes(java.nio.charset.StandardCharsets.UTF_8));
        assertThrows(IllegalArgumentException.class,()->MigrationSnapshot.restoreCheck(backup,temporary.resolve("other-restore"),"sa",""));
    }
    @Test void approvedBytesWithAmbiguousJsonKeysAreStillRejected() throws Exception {
        prepare();String original=new String(Files.readAllBytes(manifest),java.nio.charset.StandardCharsets.UTF_8);
        Files.write(manifest,original.replace("\"version\" : 1","\"version\" : 9, \"version\" : 1").getBytes(java.nio.charset.StandardCharsets.UTF_8));digest=fileHash(manifest);
        assertThrows(com.fasterxml.jackson.core.JsonParseException.class,()->apply(10));assertFalse(tables(db).contains("LEGACY_CREW_MIGRATIONS"));
    }
    @Test void orphanRecordsAreQuarantinedAndNeverAssignedToAConvenientOwner() throws Exception {
        LegacyCrewMigrationTool.update(db,"insert into rallies values('orphan',null,'No owner',null)");
        ObjectNode plan=LegacyCrewMigrationTool.plan(db,media);assertEquals(1,plan.path("quarantinedOrphans").path("rallies").asInt());prepare();apply(10);
        assertEquals(1,LegacyCrewMigrationTool.count(db,"select count(*) from rallies where id='orphan' and team_profile_id is null"));
    }
    @Test void aValidBackupOfDifferentDataCannotAuthorizeThisPlanEvenWithEditedMetadata() throws Exception {
        prepare();
        LegacyCrewMigrationTool.update(db,"update notes set text='Different' where pec_id='pec-a'");
        Path wrongBackup=temporary.resolve("wrong-backup"),wrongRestore=temporary.resolve("wrong-restore");
        MigrationSnapshot.backup(db,media,wrongBackup);MigrationSnapshot.restoreCheck(wrongBackup,wrongRestore,"sa","");
        LegacyCrewMigrationTool.update(db,"update notes set text='E3 a' where pec_id='pec-a'");
        Path wrongProof=wrongRestore.resolve("restore-proof.json");
        assertThrows(IllegalArgumentException.class,()->LegacyCrewMigrationTool.apply(db,media,manifest,digest,wrongBackup,wrongProof,"sa","",10));
        ObjectNode metadata=(ObjectNode)read(wrongBackup.resolve("backup.json"));
        ((ObjectNode)metadata.get("contextDigests")).put("team-a",read(manifest).path("entries").get(0).path("expectedDigest").asText());
        Files.write(wrongBackup.resolve("backup.json"),JSON.writeValueAsBytes(metadata));
        ObjectNode proof=(ObjectNode)read(wrongProof);proof.put("backupDigest",fileHash(wrongBackup.resolve("backup.json")));Files.write(wrongProof,JSON.writeValueAsBytes(proof));
        assertThrows(IllegalArgumentException.class,()->LegacyCrewMigrationTool.apply(db,media,manifest,digest,wrongBackup,wrongProof,"sa","",10));
        assertFalse(tables(db).contains("LEGACY_CREW_MIGRATIONS"));assertEquals(2,count("notes"));
    }
    @Test void databaseFenceAndRollbackGuardKeepRevocationAndNewData() throws Exception {
        prepare();apply(10);LegacyCrewMigrationTool.update(db,"update auth_users set active=false,token='revoked' where id='user-a'");
        LegacyCrewMigrationTool.update(db,"insert into notes(pec_id,text) values('pec-a','New data')");
        assertThrows(SQLException.class,()->LegacyCrewMigrationTool.update(db,"update auth_users set team_profile_id='team-a' where id='user-a'"));
        assertThrows(SQLException.class,()->LegacyCrewMigrationTool.update(db,"insert into auth_users(id,email,password_hash,token,active,team_profile_id) values('intruder','new@fixture.invalid','hash','token',true,'team-a')"));
        Path old=jar("old.jar",null), compatible=jar("compatible.jar",LegacyCrewMigrationTool.CAPABILITY);
        assertThrows(IllegalArgumentException.class,()->LegacyCrewMigrationTool.checkRollback(db,old));LegacyCrewMigrationTool.checkRollback(db,compatible);
        apply(10);assertEquals(1,LegacyCrewMigrationTool.count(db,"select count(*) from auth_users where id='user-a' and active=false and token='revoked'"));assertEquals(3,count("notes"));
    }
